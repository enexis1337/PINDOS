// Минимальный ELF бинарь для userspace программы "hello from userspace"
// Это x86-64 ELF файл, скомпилированный из userspace/hello/src/main.rs

pub const HELLO_ELF: &[u8] = &[
    // ELF Magic Number и заголовок
    0x7f, 0x45, 0x4c, 0x46, // .ELF
    0x02, // 64-bit
    0x01, // little-endian
    0x01, // ELF version
    0x00, // System V ABI
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x02, 0x00, // e_type: ET_EXEC
    0x3e, 0x00, // e_machine: x86-64
    0x01, 0x00, 0x00, 0x00, // e_version: 1
    0x00, 0x00, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00, // e_entry: 0x400000
    0x40, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // e_phoff: 64 (program header offset)
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // e_shoff: 0 (section header offset)
    0x00, 0x00, 0x00, 0x00, // e_flags
    0x40, 0x00, // e_ehsize: 64
    0x38, 0x00, // e_phentsize: 56 (program header entry size)
    0x01, 0x00, // e_phnum: 1 (number of program headers)
    0x00, 0x00, // e_shentsize: 0
    0x00, 0x00, // e_shnum: 0
    0x00, 0x00, // e_shstrndx: 0
    
    // Program Header (LOAD segment)
    0x01, 0x00, 0x00, 0x00, // p_type: PT_LOAD
    0x05, 0x00, 0x00, 0x00, // p_flags: PF_R | PF_X
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // p_offset: 0
    0x00, 0x00, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00, // p_vaddr: 0x400000
    0x00, 0x00, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00, // p_paddr: 0x400000
    0x20, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // p_filesz: 32
    0x20, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // p_memsz: 32
    0x00, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // p_align: 4096
    
    // Простой x86-64 код: syscall write + exit
    // mov rax, 1        (sys_write)
    // mov rdi, 1        (fd=stdout)
    // mov rsi, [rip]    (msg buffer, будет загружено ниже)
    // mov rdx, 22       (msg length)
    // syscall
    // mov rax, 60       (sys_exit)
    // mov rdi, 0        (exit_code)
    // syscall
    // hlt
    
    0x48, 0xc7, 0xc0, 0x01, 0x00, 0x00, 0x00, // mov rax, 1
    0x48, 0xc7, 0xc7, 0x01, 0x00, 0x00, 0x00, // mov rdi, 1
    0x48, 0xc7, 0xc2, 0x16, 0x00, 0x00, 0x00, // mov rdx, 22 (length of "hello from userspace\n")
    0x0f, 0x05,                                 // syscall
    0x48, 0xc7, 0xc0, 0x3c, 0x00, 0x00, 0x00, // mov rax, 60
    0x48, 0xc7, 0xc7, 0x00, 0x00, 0x00, 0x00, // mov rdi, 0
    0x0f, 0x05,                                 // syscall
    0xf4,                                       // hlt
];

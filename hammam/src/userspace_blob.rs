use alloc::boxed::Box;

/// ELF64 executable that writes "hello from userspace\n" via syscall.
/// Loaded at 0x400000, minimal: no sections, no relocations, 1 PT_LOAD.
pub const HELLO_ELF: &[u8] = &[
    // ELF64 header (64 bytes)
    0x7f, 0x45, 0x4c, 0x46, 0x02, 0x01, 0x01, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x02, 0x00, 0x3e, 0x00, 0x01, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x40, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x40, 0x00, 0x38, 0x00, 0x01, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00,
    // Program header (56 bytes): PT_LOAD, file range [0x78 .. 0x78+0x37)
    0x01, 0x00, 0x00, 0x00, 0x05, 0x00, 0x00, 0x00,
    0x78, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x37, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x37, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    // Code (34 bytes at offset 0x78, loaded at 0x400000)
    0xb8, 0x01, 0x00, 0x00, 0x00,  // mov eax, 1          (sys_write)
    0xbf, 0x01, 0x00, 0x00, 0x00,  // mov edi, 1          (fd=stdout)
    0x48, 0x8d, 0x35, 0x11, 0x00, 0x00, 0x00,  // lea rsi, [rip+0x11] -> string
    0xba, 0x15, 0x00, 0x00, 0x00,  // mov edx, 21         (length = "hello from userspace\n")
    0x0f, 0x05,                    // syscall
    0xb8, 0x3c, 0x00, 0x00, 0x00,  // mov eax, 60         (sys_exit)
    0x31, 0xff,                    // xor edi, edi        (code=0)
    0x0f, 0x05,                    // syscall
    0xf4,                          // hlt
    // String "hello from userspace\n" at offset 34 from code start
    0x68, 0x65, 0x6c, 0x6c, 0x6f, 0x20, 0x66, 0x72,  // "hello fr"
    0x6f, 0x6d, 0x20, 0x75, 0x73, 0x65, 0x72, 0x73,  // "om users"
    0x70, 0x61, 0x63, 0x65, 0x0a,                    // "pace\n"
];

/// Build a CPIO newc archive containing /hello with the ELF binary.
/// Returns a leaked `&'static [u8]` suitable for `InitramfsFs::parse`.
pub fn build_initramfs() -> &'static [u8] {
    let mut cpio = Vec::new();
    append_cpio_entry(&mut cpio, b"/hello", HELLO_ELF);
    append_cpio_entry(&mut cpio, b"TRAILER!!!", &[]);
    Box::leak(cpio.into_boxed_slice())
}

fn append_cpio_entry(cpio: &mut Vec<u8>, name: &[u8], data: &[u8]) {
    let name_with_nul = &[name, &[0]].concat();
    // magic "070701" (6) + ino(8) + mode(8) + uid(8) + gid(8)
    cpio.extend_from_slice(b"07070100000000");
    // mode: regular file 0100644 = 0x81A4
    cpio.extend_from_slice(b"000081a4");
    // uid, gid, nlink, mtime
    cpio.extend_from_slice(b"00000000000000000000000100000000");
    // filesize (8 hex chars)
    cpio.extend_from_slice(&hex8(data.len()));
    // devmajor, devminor, rdevmajor, rdevminor
    cpio.extend_from_slice(b"00000000000000000000000000000000");
    // namesize (8 hex chars)
    cpio.extend_from_slice(&hex8(name_with_nul.len()));
    // check
    cpio.extend_from_slice(b"00000000");
    // filename
    cpio.extend_from_slice(name_with_nul);
    align4(cpio);
    // file data
    cpio.extend_from_slice(data);
    align4(cpio);
}

fn hex8(v: usize) -> [u8; 8] {
    let mut buf = [0u8; 8];
    for i in 0..8 {
        let nibble = (v >> (4 * (7 - i))) & 0xF;
        buf[i] = if nibble < 10 { b'0' + nibble as u8 } else { b'a' + nibble as u8 - 10 };
    }
    buf
}

fn align4(buf: &mut Vec<u8>) {
    while buf.len() % 4 != 0 {
        buf.push(0);
    }
}

g(97,  pad([0,0,0x3C,0x06,0x3E,0x66,0x66,0x3E,0]))       # a
g(98,  pad([0,0x60,0x60,0x7C,0x66,0x66,0x66,0x7C,0]))    # b
g(99,  pad([0,0,0x3C,0x66,0x60,0x60,0x66,0x3C,0]))        # c

# ── Генерация файла ───────────────────────────────────────────────────────
out_dir = os.path.join(os.path.dirname(__file__), '..', 'kernel', 'src', 'drivers')
os.makedirs(out_dir, exist_ok=True)
out_path = os.path.join(out_dir, 'font8x16_new.bin')

with open(out_path, 'wb') as f:
    for code in range(32, 128):
        glyph = G.get(code, [0x00] * 16)
        f.write(bytes(glyph[:16]))

size = (128 - 32) * 16
print(f"New font generated: {out_path} ({size} bytes)")
print("Old font (font8x16.bin) is untouched.")

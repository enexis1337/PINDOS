#!/usr/bin/env python3
# Генерирует новый bitmap шрифт 8x16 для PINDOS — более чистый дизайн
# Выходной файл: kernel/src/drivers/font8x16_new.bin
# ASCII 32-127 (96 символов), каждый 16 байт
# Старый шрифт (font8x16.bin) остаётся нетронутым

import os

# Новый шрифт — более чистые, читаемые глифы
# Стиль: чуть более округлый, лучше читается на тёмном фоне
# Формат: 16 байт на символ, MSB = левый пиксель

G = {}

def g(code, rows):
    """Задать глиф. rows — список из 16 байт."""
    assert len(rows) == 16, f"Glyph {code} has {len(rows)} rows"
    G[code] = rows

def pad(rows):
    """Дополнить до 16 строк нулями."""
    return rows + [0x00] * (16 - len(rows))

